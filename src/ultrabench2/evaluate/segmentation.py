"""An evaluator for computing segmentation metrics given CSV files
containing a model's predictions and the ground-truth labels.
"""

import logging
import math
from pathlib import Path

import numpy as np
import pandas as pd

from ultrabench2.core.rle import rle_to_mask

logger = logging.getLogger(__name__)


def dice_score(gt_mask: np.ndarray, pred_mask: np.ndarray) -> float:
    """Compute the Dice score of one predicted mask.

    Follows `torchmetrics.segmentation.DiceScore`: a class absent from
    both masks is undefined rather than perfect, so it is excluded from
    the averages instead of being scored 1.0.

    Args:
        gt_mask: The ground-truth binary mask.
        pred_mask: The predicted binary mask.

    Returns:
        The Dice score, or NaN if both masks are empty.
    """
    denominator = int(gt_mask.sum()) + int(pred_mask.sum())
    if denominator == 0:
        return math.nan

    return 2.0 * int((gt_mask * pred_mask).sum()) / denominator


class SegmentationEvaluator:
    """Evaluate a semantic segmentation model.

    Compute segmentation metrics given CSV files containing run-length
    encoded per-class segmentation masks generated by the model and the
    ground-truth masks.

    The reported metric is `positive_dice`, matching the metric the
    training layer writes to `test_metrics.csv` with
    `torchmetrics.segmentation.DiceScore(include_background=False)`. Two
    conventions of that metric are reproduced here, and both matter:

    * An (image, class) pair that is empty in both the ground truth and
      the prediction is undefined, and is dropped from the averages
      rather than scored 1.0.
    * The averaging is sample-major: the defined foreground classes of
      an image are averaged first, then the images. Averaging the other
      way round gives a different number once the undefined pairs make
      the per-class groups unequal in size.

    Args:
        ground_truth_path: Path to the ground truth CSV file with
            columns `image_id`, `class_id`, `encoded_pixels`.
        predictions_path: Path to the predictions CSV file with the same
            columns.
        image_height: Height of the masks in pixels.
        image_width: Width of the masks in pixels.
        output_dir: Directory where output CSVs containing per-image
            and aggregated metrics will be written.
    """

    def __init__(
        self,
        ground_truth_path: str | Path,
        predictions_path: str | Path,
        output_dir: str | Path,
        image_height: int,
        image_width: int,
    ) -> None:
        self.ground_truth_path = Path(ground_truth_path)
        self.predictions_path = Path(predictions_path)
        self.output_dir = Path(output_dir)
        self.image_height = image_height
        self.image_width = image_width

    def evaluate(self) -> dict[str, float]:
        """Evaluate the predictions against the ground truth.

        Compare the ground truth and predictions CSV files, compute the
        segmentation metrics, and write a per-image and summary CSV
        with the results.

        Returns:
            A dictionary containing the aggregated segmentation metrics.
            `positive_dice` is NaN if no (image, class) pair is defined.

        Raises:
            ValueError: If either CSV is missing a required column.
        """
        gt = pd.read_csv(self.ground_truth_path, converters={"encoded_pixels": str})
        pred = pd.read_csv(self.predictions_path, converters={"encoded_pixels": str})

        for df, name in [(gt, "ground_truth"), (pred, "predictions")]:
            missing = {"image_id", "class_id", "encoded_pixels"} - set(df.columns)
            if missing:
                raise ValueError(f"{name} CSV missing columns: {missing}")

        gt_images = set(gt["image_id"].unique())
        pred_images = set(pred["image_id"].unique())
        for image in gt_images - pred_images:
            logger.warning("Image in GT not in predictions: %s", image)
        for image in pred_images - gt_images:
            logger.warning("Image in predictions not in GT: %s", image)

        pred_index = pred.set_index(["image_id", "class_id"])["encoded_pixels"]
        rows = []
        for _, gt_row in gt.iterrows():
            key = (gt_row["image_id"], gt_row["class_id"])

            pred_rle = pred_index.get(key, "")
            gt_rle = gt_row["encoded_pixels"]
            gt_mask = rle_to_mask(gt_rle, self.image_height, self.image_width)
            pred_mask = rle_to_mask(pred_rle, self.image_height, self.image_width)

            rows.append(
                {
                    "image_id": gt_row["image_id"],
                    "class_id": gt_row["class_id"],
                    "dice": dice_score(gt_mask, pred_mask),
                }
            )

        results_df = pd.DataFrame(rows, columns=["image_id", "class_id", "dice"])

        # Aggregate metrics, excluding the background (Class 0). The
        # groupby means skip the undefined pairs, so an image whose every
        # foreground class is undefined becomes NaN and then drops out of
        # the mean over images.
        non_bg = results_df[results_df["class_id"] != 0]
        per_image = non_bg.groupby("image_id")["dice"].mean()
        per_class = non_bg.groupby("class_id")["dice"].mean()
        positive_dice = float(per_image.mean()) if len(per_image) > 0 else math.nan

        if math.isnan(positive_dice):
            logger.warning(
                "No (image, class) pair is defined: every foreground class is "
                "empty in both the ground truth and the predictions."
            )

        metrics: dict[str, float] = {"positive_dice": positive_dice}
        for class_id, mean_dice in per_class.items():
            metrics[f"dice_class_{class_id}"] = float(mean_dice)

        # Save outputs
        self.output_dir.mkdir(parents=True, exist_ok=True)
        results_df.to_csv(self.output_dir / "per_image_metrics.csv", index=False)

        summary_rows = [{"metric": k, "value": v} for k, v in metrics.items()]
        pd.DataFrame(summary_rows).to_csv(self.output_dir / "summary.csv", index=False)

        return metrics
